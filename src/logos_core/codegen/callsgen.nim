## lcn-gen's typed call helpers [IMPL]: `<stem>_calls.nim` and `<stem>_calls.h`
## for an accepted set (INTERFACE §2.7.2, App A.1, A.5), so that a consumer
## calls the methods of the set's exposed contracts through a route handle
## (§5.2) with typed values instead of encoding CBOR by hand.
##
## The set is the provider's: a concrete module document with its interfaces
## and supporting schemas, or a standalone interface document with its
## supporting schemas. Every method of the primary document and of each
## implemented interface gets a helper, named by its defining contract. The
## route decides which of them it accepts, since it selects one contract
## (§5.2); a helper neither selects a provider nor acquires a route (App A.5).
##
## `<stem>_calls.nim` imports the set's `<stem>_types.nim` (`nimgen`) and
## declares:
##
## - For Nim callers, one
##   `invoke(route: ptr LogosRouteHandle, request: <Request>):
##   Result[<Response>, InvocationFailure]` per method, overloaded on the
##   request type.
## - For C callers, a template `export<Stem>Calls()`. A Nim module
##   instantiates it once, at top level, to define `<stem>_calls.h`'s
##   `lcn_invoke_<namespace>_<Method>` and `lcn_clear_<namespace>_<Method>`
##   with C linkage. Exporting is opt-in: two libraries that both exported
##   helpers for one interface would clash.
##
## The C helpers use the C-layout mirrors and converters of the module kit
## (`cmirror`, `callrt`), and the calls go through `invokert.routeCall`.
## Helper names start with `lcn_`, not `logos_`: they are derived helpers
## (§2.1), and a module must not export other `logos_` symbols (IFC-0057).

{.push raises: [].}

import std/[sequtils, strutils, tables]
import ../pins
import ../iface/[accept, cmap]
import ./[cmirror, nimgen]

type CallsOptions* = object
  importPrefix*: string ## how the output imports this library (`NimOptions`)

func pascal(name: string): string =
  for part in name.split('_'):
    if part.len > 0:
      result.add(part[0].toUpperAscii & part[1 ..^ 1])

func callsTemplateName*(stem: string): string =
  ## The export template of a set's calls module.
  "export" & pascal(stem) & "Calls"

proc callsModule*(
    s: ContractSet, opts = CallsOptions(importPrefix: "logos_core/"), system = false
): Result[string, string] =
  ## `<stem>_calls.nim` for the set `s`, beside the `<stem>_types.nim` that
  ## `nimModule` writes for the same set.
  let stem = s.cSchemaSet.headerName
  let layout = ?cLayout(s.cSchemaSet)
  if layout.methods.len == 0:
    return err("the set exposes no method")
  let names = nimTypeNames(s)
  let tmpl = callsTemplateName(stem)
  let prefix = block:
    let p = pascal(stem) & "Calls"
    p[0].toLowerAscii & p[1 ..^ 1]
  let mirrors = ?callMirrors(s, prefix, names)
  var o =
    "## " & stem & "_calls.nim: generated by lcn-gen. PROVISIONAL (spec " &
    SpecRevision[0 .. 7] & ").\n" & "## Typed calls to the methods of `" & stem &
    "`'s exposed contracts through a route\n" &
    "## handle (INTERFACE §2.7.2, §5.2, App A.5). Do not edit.\n##\n" &
    "## Nim callers (the caller serializes calls on one route handle, §2.8):\n##\n"
  for m in layout.methods:
    o.add(
      "##   proc invoke*(route: ptr LogosRouteHandle, request: " &
        names.getOrDefault(m.request) & "): Result[" & names.getOrDefault(m.response) &
        ", InvocationFailure] # " & m.methodName & "\n"
    )
  o.add(
    "##\n## C callers: instantiate `" & tmpl & "()` once, at top level, to export\n" &
      "## the helpers `" & stem & "_calls.h` declares.\n"
  )
  o.add(
    "\n#!fmt: off\n{.push raises: [], gcsafe.}\n\n" & "import " & opts.importPrefix &
      "codegen/[invokert, common_mirrors]\nimport ./" & stem &
      "_types\n\nexport invokert, common_mirrors, " & stem & "_types\n\n"
  )
  o.add(
    "const\n  primaryDocument = " & escape(s.primary.source) &
      "\n  interfaceDocuments: array[" & $s.interfaces.len & ", string] = [" &
      s.interfaces.mapIt(escape(it.source)).join(", ") &
      "]\n  supportingDocuments: array[" & $s.supporting.len & ", string] = [" &
      s.supporting.mapIt(escape(it.source)).join(", ") & "]\n"
  )
  o.add(
    "\nperThread(\n  callsSchema,\n  GeneratedSchema,\n" &
      "  loadSchema(primaryDocument, interfaceDocuments, supportingDocuments, " & $system &
      "),\n)\ndiscard callsSchema()\n"
  )
  if mirrors.types.len > 0:
    o.add("\n" & mirrors.types & "\n")
  o.add("\n" & mirrors.procs & "\n")
  o.add("\n" & mirrors.layout & "\n")
  o.add(
    "\ntemplate " & tmpl & "*() =\n" & "  ## Defines `" & stem &
      "_calls.h`'s helpers with C linkage.\n"
  )
  o.add(mirrors.exports.join("\n\n") & "\n")
  ok(o)

proc callsHeaderFile*(s: ContractSet): Result[string, string] =
  ## `<stem>_calls.h` for the set `s` (`cmap.callsHeader`).
  callsHeader(s.cSchemaSet)
