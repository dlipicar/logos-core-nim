"""Writes the Unicode tables behind base/nfc.nim, and NFC test vectors, from
Python's unicodedata (an independent implementation of UAX #15).

PM §7.1 requires LGX archive paths to be NFC-normalized. The Nim side needs:
  - canonical combining classes (non-zero only), as ranges;
  - full canonical decompositions (what NFD gives for one code point), Hangul
    syllables excluded (they decompose algorithmically);
  - primary composites: pairs (a, b) that NFC composes, derived by asking
    unicodedata whether NFC(a b) is the composite. This leaves out composition
    exclusions, singletons and non-starter decompositions without a list.

  python3 oracle/gen_nfc_tables.py           write both files
  python3 oracle/gen_nfc_tables.py --check   fail if either is not what this writes
"""

from __future__ import annotations

import json
import sys
import unicodedata as ud
from pathlib import Path

TABLES = Path("src/logos_core/base/nfc_tables.nim")
VECTORS = Path("tests/vectors/nfc.json")

S_BASE, S_COUNT = 0xAC00, 11172


def is_hangul(cp: int) -> bool:
    return S_BASE <= cp < S_BASE + S_COUNT


def chars():
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        yield cp, chr(cp)


ccc_ranges: list[tuple[int, int, int]] = []
decomp: list[tuple[int, list[int]]] = []
pairs: list[tuple[int, int, int]] = []

for cp, ch in chars():
    c = ud.combining(ch)
    if c:
        if ccc_ranges and ccc_ranges[-1][1] == cp - 1 and ccc_ranges[-1][2] == c:
            ccc_ranges[-1] = (ccc_ranges[-1][0], cp, c)
        else:
            ccc_ranges.append((cp, cp, c))
    if is_hangul(cp):
        continue
    nfd = ud.normalize("NFD", ch)
    if nfd != ch:
        decomp.append((cp, [ord(x) for x in nfd]))
    d = ud.decomposition(ch)
    if d and not d.startswith("<"):
        parts = [int(x, 16) for x in d.split()]
        if len(parts) == 2 and ud.normalize("NFC", chr(parts[0]) + chr(parts[1])) == ch:
            pairs.append((parts[0], parts[1], cp))

pairs.sort()
data: list[int] = []
index: list[tuple[int, int, int]] = []
for cp, seq in decomp:
    index.append((cp, len(data), len(seq)))
    data.extend(seq)


def rows(items, per_line: int, fmt) -> str:
    out = []
    for i in range(0, len(items), per_line):
        out.append("    " + ", ".join(fmt(x) for x in items[i : i + per_line]) + ",")
    return "\n".join(out)


nim = f"""## Generated by oracle/gen_nfc_tables.py from Python's unicodedata
## (Unicode {ud.unidata_version}). Do not edit.

#!fmt: off
const
  UnicodeVersion* = "{ud.unidata_version}"

  CccRanges*: array[{len(ccc_ranges)}, (uint32, uint32, uint8)] = [
{rows(ccc_ranges, 4, lambda r: f"(0x{r[0]:X}'u32, 0x{r[1]:X}'u32, {r[2]}'u8)")}
  ]
    ## (first, last, class) for every non-zero canonical combining class

  DecompIndex*: array[{len(index)}, (uint32, uint16, uint8)] = [
{rows(index, 4, lambda r: f"(0x{r[0]:X}'u32, {r[1]}'u16, {r[2]}'u8)")}
  ]
    ## (code point, offset into DecompData, length): full canonical
    ## decompositions, Hangul syllables excluded

  DecompData*: array[{len(data)}, uint32] = [
{rows(data, 8, lambda x: f"0x{x:X}'u32")}
  ]

  CompositionPairs*: array[{len(pairs)}, (uint32, uint32, uint32)] = [
{rows(pairs, 3, lambda r: f"(0x{r[0]:X}'u32, 0x{r[1]:X}'u32, 0x{r[2]:X}'u32)")}
  ]
    ## (first, second, primary composite), sorted
"""

# Vectors: strings with their NFC form, covering each table and Hangul.
samples = [
    "", "abc", "é", "é", "ậ", "ậ", "ṩ", "ṩ",
    "Å", "Ω", "̈́", "क़", "⫝̸", "가", "각",
    "각", "각", "ᄀ가", "x́", "́a", "ୋ",
    "େ̀ା", "Ą̊", "Ą̊", "variants/linux-x86_64/lib/libfoo.so",
    "café/não", "\U0001d15e", "\U0001d157\U0001d165", "ֱָֹ֑׃ְ֬֟",
    "à֮̀̕b", "῁", "῁", "ཱི", "ཱི",
]
for _, ch in [(c, chr(c)) for c, _ in decomp[:: max(1, len(decomp) // 300)]]:
    samples.append(ch)
    samples.append(ud.normalize("NFD", ch))
for a, b, c in pairs[:: max(1, len(pairs) // 200)]:
    samples.append(chr(a) + chr(b))
vectors = [{"in": s, "nfc": ud.normalize("NFC", s), "is_nfc": ud.is_normalized("NFC", s)} for s in samples]
doc = {"source": "oracle/gen_nfc_tables.py", "unicode": ud.unidata_version, "vectors": vectors}
vec = json.dumps(doc, indent=1, ensure_ascii=True) + "\n"

if "--check" in sys.argv[1:]:
    stale = [str(p) for p, t in [(TABLES, nim), (VECTORS, vec)] if not p.exists() or p.read_text() != t]
    if stale:
        sys.exit(f"stale: {', '.join(stale)}: run python3 oracle/gen_nfc_tables.py")
    print(f"ok   {TABLES} and {VECTORS} match unicodedata {ud.unidata_version}")
else:
    TABLES.write_text(nim)
    VECTORS.write_text(vec)
    print(f"wrote {TABLES}: {len(ccc_ranges)} ccc ranges, {len(index)} decompositions, {len(pairs)} pairs")
    print(f"wrote {VECTORS}: {len(vectors)} vectors")
