#!/usr/bin/env python3
"""The suites that load a Nim library at run time: no `-msan` check on aarch64 (DECISIONS I77 (8)).

    python3 -I tools/sanitizer/dlopen_suites.py [--root DIR]
    python3 -I tools/sanitizer/dlopen_suites.py --write nix/msan-dlopen-suites.json
    python3 -I tools/sanitizer/dlopen_suites.py --check nix/msan-dlopen-suites.json
    python3 -I tools/sanitizer/dlopen_suites.py --self-test [--root DIR]

On aarch64 a library loaded with `dlopen` reaches its thread-local variables through TLS
descriptors, which bypass the `__tls_get_addr` interceptor MemorySanitizer relies on to see glibc
initialize them, so Nim's start-up in such a library reads as uninitialized. Whether a given
suite trips over it depends on how much thread-local storage its libraries need beyond the static
block glibc keeps spare, so the rule is the cause, not the symptom: a suite that loads a Nim
library has no `-msan` check on aarch64, and x86_64 runs it. flake.nix reads the list from
`nix/msan-dlopen-suites.json`; the `affected-suites` check runs `--check` on it, so a suite that
starts loading a library fails that check until the list is written again, not run 2's aarch64
MemorySanitizer job.

A suite loads a Nim library when a file it builds or reads (tools/affected_suites.py's reach,
the suite itself included) builds one, outside the module that defines the builder: a call of
`buildKitLibrary` or `buildKitLibraryIn` (logos_sdk/testing/kitbuild, which every library a test
loads comes from, a Module Host's or logosd's included), or `--app:lib` given to the compiler
directly (test_host_dylib, test_kit_dylib, tests/support/hostbuild). Comments do not count. A
suite that imports kitbuild for its paths or variants only, or that links a kit in-process
(test_routes: `meter_impl`, `sensor_impl`), loads nothing.
"""

import argparse
import json
import os
import re
import sys
import tempfile

TOOLS = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, TOOLS)
import affected_suites  # noqa: E402 (tools/affected_suites.py: the tree and the reach)

BUILD = re.compile(r"\bbuildKitLibrary(?:In)?\s*\(|--app:lib\b")
DEFINES = re.compile(r"^\s*(?:proc|template|func)\s+buildKitLibrary(?:In)?\*", re.M)
COMMENT = re.compile(r"^\s*#.*$", re.M)
COMMENT_NOTE = (
    "The suites that load a Nim library at run time: no -msan check on aarch64 (DECISIONS I77 (8)). "
    "Generated by tools/sanitizer/dlopen_suites.py --write; the affected-suites check compares it; "
    "do not edit."
)


def code(text):
    """A Nim file's text without its comment lines (`#`, `##`, and `#[`-free line comments)."""
    return COMMENT.sub("", text)


def builders(tree):
    """The Nim files that build a library, outside the module that defines the builder."""
    out = set()
    for f in tree.files:
        if not f.endswith(affected_suites.NIM):
            continue
        text = code(tree.read(f))
        if DEFINES.search(text):
            continue
        if BUILD.search(text):
            out.add(f)
    return out


def dlopen_suites(tree):
    """{suite name: the first builder its reach holds}."""
    graph = affected_suites.Graph(tree, set())
    built = builders(tree)
    result = {}
    for suite in affected_suites.suites_of(tree):
        hits = sorted(built & set(graph.closure(suite)))
        if hits:
            result[os.path.basename(suite)[:-4]] = hits[0]
    return result


SELF_TREE = {
    "config.nims": "",
    "sdk/src/logos_sdk/testing/kitbuild.nim": (
        "proc buildKitLibraryIn*(dir: string) =\n"
        '  discard execCmd("nim c --app:lib " & dir)\n'
        "template buildKitLibrary*(src: string) =\n"
        "  buildKitLibraryIn(src)\n"
        "proc kitVariantOf*(mm: string): string = mm\n"
    ),
    "tests/support/libs.nim": "import logos_sdk/testing/kitbuild\nbuildKitLibrary(\"k_impl.nim\")\n",
    "tests/support/paths.nim": "import logos_sdk/testing/kitbuild\nlet v* = kitVariantOf(\"orc\")\n",
    "tests/test_a.nim": "import support/libs\n",  # through a support module
    "tests/test_b.nim": "import support/paths\n",  # kitbuild for a variant only
    "tests/test_c.nim": "import logos_sdk/testing/kitbuild\nbuildKitLibraryIn(\"x\")\n",  # directly
    "sdk/tests/test_d.nim": 'discard execCmd("nim c --app:lib --out:h.so h.nim")\n',  # the compiler
    "tests/test_e.nim": "import support/paths\n# buildKitLibrary(\"k\") is only named in a comment\n",
}
SELF_WANT = {"test_a", "test_c", "test_d"}
# On this repository: the first four loaded libraries when I77 (8) was written; the next four
# failed in big CI run 1 (2026-11-25); test_routes links its kits and test_kit loads nothing.
REPO_IN = {
    "test_engine",
    "test_kit_dylib",
    "test_realizer",
    "test_hosted_routes",
    "test_pm_queries",
    "test_system_binding",
    "test_persist",
    "test_pm_hosted",
}
REPO_OUT = {"test_routes", "test_routes_ca", "test_kit", "test_cbor"}


def self_test(root):
    failures = []
    with tempfile.TemporaryDirectory() as scratch:
        for path, text in SELF_TREE.items():
            os.makedirs(os.path.join(scratch, os.path.dirname(path)), exist_ok=True)
            with open(os.path.join(scratch, path), "w") as f:
                f.write(text)
        got = set(dlopen_suites(affected_suites.Tree.from_dir(scratch)))
        if got != SELF_WANT:
            failures.append(f"planted tree: got {sorted(got)}, want {sorted(SELF_WANT)}")
    if os.path.isfile(os.path.join(root, "sdk/src/logos_sdk/testing/kitbuild.nim")):
        got = set(dlopen_suites(affected_suites.Tree.from_dir(root)))
        if not REPO_IN <= got:
            failures.append(f"this tree: {sorted(REPO_IN - got)} not found loading a library")
        if got & REPO_OUT:
            failures.append(f"this tree: {sorted(got & REPO_OUT)} found loading a library")
    else:
        failures.append(f"{root} has no kitbuild.nim: not this repository's tree")
    for f in failures:
        print(f"self-test: {f}", file=sys.stderr)
    print(f"self-test: {'failed' if failures else 'passed'}", file=sys.stderr)
    return 1 if failures else 0


def main():
    here = os.path.dirname(TOOLS)
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", default=here, help="the tree to read (this repository)")
    ap.add_argument("--why", action="store_true", help="print the builder each suite reaches")
    ap.add_argument("--write", metavar="FILE", help="write the list as JSON")
    ap.add_argument("--check", metavar="FILE", help="exit 1 unless FILE holds this tree's list")
    ap.add_argument("--self-test", action="store_true")
    a = ap.parse_args()
    if a.self_test:
        return self_test(a.root)
    found = dlopen_suites(affected_suites.Tree.from_dir(a.root))
    names = sorted(found)
    if a.check:
        with open(a.check, encoding="utf-8") as f:
            listed = json.load(f).get("suites", [])
        if listed != names:
            missing, extra = sorted(set(names) - set(listed)), sorted(set(listed) - set(names))
            print(
                f"dlopen_suites: {a.check} is not this tree's list: missing {missing}, "
                f"not loading a library {extra}; write it again with "
                f"`python3 -I tools/sanitizer/dlopen_suites.py --write {a.check}`",
                file=sys.stderr,
            )
            return 1
        print(f"dlopen_suites: {a.check} matches ({len(names)} suites)", file=sys.stderr)
        return 0
    if a.write:
        with open(a.write, "w", encoding="utf-8") as f:
            json.dump({"comment": COMMENT_NOTE, "suites": names}, f, indent=1)
            f.write("\n")
        return 0
    for n in names:
        print(f"{n}  ({found[n]})" if a.why else n)
    return 0


if __name__ == "__main__":
    sys.exit(main())
